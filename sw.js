// One cache name per deployment: the registration scope keeps two copies on one origin apart (e.g. two repos of one
// github.io account), so activating one never deletes the other's cache (CB-09).
var PREFIX = 'long-horizon:' + self.registration.scope + ':';
var CACHE = PREFIX + VERSION;
// 1.0.0 ran under the working name Holdfast: its caches for this same scope are old versions of this deployment.
var OLD_PREFIXES = ['holdfast:' + self.registration.scope + ':'];
function ownedOld(k) {
  if (k.indexOf(PREFIX) === 0) return k !== CACHE;
  for (var i = 0; i < OLD_PREFIXES.length; i++) if (k.indexOf(OLD_PREFIXES[i]) === 0) return true;
  return false;
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      return cache.addAll(PRECACHE.map(function (url) { return new Request(url, { cache: 'reload' }); }));
    }).then(function () {
      if (!self.registration.active) return self.skipWaiting();
      return undefined;
    })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.filter(ownedOld).map(function (k) { return caches.delete(k); }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('message', function (event) {
  if (event.data && event.data.type === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;
  var url;
  try { url = new URL(req.url); } catch (e) { return; }
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(function (cache) {
      return cache.match(req, { ignoreSearch: true }).then(function (hit) {
        if (hit) return hit;
        return fetch(req).then(function (res) {
          if (res && res.ok && res.type === 'basic') cache.put(req, res.clone());
          return res;
        }).catch(function () {
          if (req.mode === 'navigate') {
            return cache.match('index.html').then(function (r) { return r || Response.error(); });
          }
          return Response.error();
        });
      });
    })
  );
});
