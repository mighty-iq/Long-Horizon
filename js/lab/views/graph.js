/* Long-Horizon — Lab view: Graph Mapping (HF.views['lab.graph']). Browser only, ES2019, MIT. Owner: P2.
   After Jastrzębski, Ociepka & Chuderski (2023), as generated by js/lab/tests/graph.js: two drawings of the same
   arrow network; the left one marks two dots, 1 (ring) and 2 (square) — number AND outline shape, never colour alone.
   The player taps the matching dots on the right: first the match for 1, then for 2. Choices can be changed until
   Confirm. Keyboard: the right-hand dots carry letters A–F in reading order; type a letter to place the current mark,
   1 or 2 to choose which mark to place, Backspace to clear it, Enter to confirm. Tab to a dot + Space places it too.
   24 s per item (spec.windowMs) with a calm countdown and a "5 seconds left" note at spec.warnMs (19 s).
   At the cap the item ends with whatever was placed: { response: [id|null, id|null], timedOut: true } (partial credit
   is kept by the scorer, the item counts as wrong).

   create(root, spec, ctx) → { run(ctx2) → Promise<log>, destroy() }
     log (SPEC §4.3): { answers: [ { i, response: [rightIdFor1, rightIdFor2], rt, voided, timedOut } ], paused, pauses, aborted }
*/
(function (root) {
  'use strict';
  var HF = root.HF || (root.HF = {});
  HF.views = HF.views || {};
  var LETTERS = 'ABCDEFGHJK';

  function K() { return HF.labKit; }

  function readingOrder(nodes) {
    return nodes.slice().sort(function (a, b) {
      var ra = Math.floor(a.y / 33.4), rb = Math.floor(b.y / 33.4);
      return ra !== rb ? ra - rb : (a.x - b.x) || (a.y - b.y);
    });
  }

  function markShape(S, x, y, R, mark) {
    if (mark === 1) return S('circle', { cx: x, cy: y, r: R + 3.4, 'class': 'hf-gm__mark hf-gm__mark--1' });
    var s = R + 3.2;
    return S('rect', { x: x - s, y: y - s, width: 2 * s, height: 2 * s, rx: 1.2, 'class': 'hf-gm__mark hf-gm__mark--2' });
  }

  /** draws one graph; returns { svg, nodeEls: { id: g } } */
  function drawGraph(g, o) {
    o = o || {};
    var S = K().svg, R = o.R || 7, kids = [], pos = {};
    g.nodes.forEach(function (n) { pos[n.id] = n; });
    // arrows rim to rim with a filled head
    g.edges.forEach(function (e) {
      var a = pos[e[0]], b = pos[e[1]];
      if (!a || !b) return;
      var dx = b.x - a.x, dy = b.y - a.y, L = Math.sqrt(dx * dx + dy * dy) || 1, ux = dx / L, uy = dy / L;
      var head = 5.2, sx = a.x + ux * (R + 0.6), sy = a.y + uy * (R + 0.6), tx = b.x - ux * (R + 0.9), ty = b.y - uy * (R + 0.9);
      var bx = tx - ux * head, by = ty - uy * head, px = -uy * head * 0.55, py = ux * head * 0.55;
      kids.push(S('line', { x1: sx.toFixed(2), y1: sy.toFixed(2), x2: bx.toFixed(2), y2: by.toFixed(2), 'class': 'hf-gm__edge' }));
      kids.push(S('path', { d: 'M' + tx.toFixed(2) + ' ' + ty.toFixed(2) + 'L' + (bx + px).toFixed(2) + ' ' + (by + py).toFixed(2) + 'L' + (bx - px).toFixed(2) + ' ' + (by - py).toFixed(2) + 'Z', 'class': 'hf-gm__head' }));
    });
    var nodeEls = {};
    var targets = {};
    (g.targets || []).forEach(function (t) { targets[t.node] = t.mark; });
    g.nodes.forEach(function (n) {
      var parts = [];
      if (o.hit) parts.push(S('circle', { cx: n.x, cy: n.y, r: 11.5, 'class': 'hf-gm__hit' }));
      parts.push(S('circle', { cx: n.x, cy: n.y, r: R, 'class': 'hf-gm__node' }));
      if (targets[n.id]) {
        parts.push(markShape(S, n.x, n.y, R, targets[n.id]));
        parts.push(S('svg:text', { x: n.x, y: n.y + 2.6, 'class': 'hf-gm__marktext', 'text-anchor': 'middle' }, [String(targets[n.id])]));
      }
      var dyn = S('g', { 'class': 'hf-gm__dyn' });
      parts.push(dyn);
      // the letter sits above-right, outside the ring / square marks (half-size R + 3.4), with a halo over edges
      if (o.letters && o.letters[n.id]) parts.push(S('svg:text', { x: n.x + R + 4.6, y: n.y - R - 0.6, 'class': 'hf-gm__letter', 'aria-hidden': 'true' }, [o.letters[n.id]]));
      var attrs = { 'class': 'hf-gm__n', 'data-node': String(n.id) };
      if (o.hit) {
        attrs.tabindex = '0'; attrs.role = 'button';
        attrs['aria-label'] = 'Dot ' + (o.letters ? o.letters[n.id] : n.id);
      }
      var el = S('g', attrs, parts);
      nodeEls[n.id] = { g: el, dyn: dyn, x: n.x, y: n.y };
      kids.push(el);
    });
    var svgEl = S('svg', { viewBox: '-4 -4 108 108', 'class': 'hf-gm__svg' + (o.cls ? ' ' + o.cls : ''), focusable: 'false', role: o.hit ? 'group' : 'img', 'aria-label': o.label || null }, kids);
    return { svg: svgEl, nodes: nodeEls, R: R };
  }

  function create(rootEl, spec, ctx) {
    ctx = ctx || {};
    var k = K(), h = k.h;
    var practice = k.isPractice(spec, ctx), feedback = k.wantsFeedback(spec, ctx);
    var S = null, F = null, destroyed = false, offs = [];
    var windowMs = spec.windowMs || 24000, warnMs = spec.warnMs || (windowMs - 5000);

    function run(ctx2) {
      ctx2 = ctx2 || {};
      F = k.frameUI(rootEl, { title: practice ? 'Practice' : (ctx.title || 'Graph mapping'), test: 'graph', cls: 'hf-lt--graph', onPause: function (r) { if (S) S.pause(r); } });
      S = k.session({});
      var trials = spec.trials || [];
      var out = { answers: [], paused: false, pauses: [], aborted: false };
      var clock = k.countdown(F, windowMs, { warnMs: warnMs, warnText: Math.round((windowMs - warnMs) / 1000) + ' seconds left' });
      return new Promise(function (resolve) {
        var idx = 0;
        function finish(aborted) {
          clock.remove();
          var L = S.log();
          out.paused = L.paused; out.pauses = L.pauses; out.aborted = !!aborted;
          S.destroy();
          resolve(out);
        }
        function next() {
          if (destroyed) return finish(true);
          S.ready().then(function (ok) {
            if (!ok) return finish(true);
            if (idx >= trials.length) return finish(false);
            var t = trials[idx];
            F.setProgress((practice ? 'Example ' : 'Item ') + (idx + 1) + ' of ' + trials.length);
            if (typeof ctx2.onProgress === 'function') ctx2.onProgress(idx, trials.length);
            item(t).then(function (res) {
              if (res === k.STOP) return finish(true);
              if (res === k.VOID) out.answers.push({ i: t.i, response: [null, null], rt: null, voided: true });
              else out.answers.push(res);
              idx++;
              var after = (feedback && res !== k.VOID) ? explain(t, res) : Promise.resolve();
              after.then(function () { return S.wait(spec.itiMs != null ? spec.itiMs : 500); }).then(next);
            });
          });
        }
        next();
      });

      function item(t) {
        return S.trial(function (ctl) {
          k.clear(F.stage); k.clear(F.answer); F.say('');
          var stim = t.stim, R = stim.nodeR || 7;
          var nTargets = (stim.left.targets || []).length || 2;
          var order = readingOrder(stim.right.nodes), letters = {}, byLetter = {};
          order.forEach(function (n, j) { letters[n.id] = LETTERS.charAt(j); byLetter[LETTERS.charAt(j)] = n.id; });
          var left = drawGraph(stim.left, { R: R, label: 'Left drawing: dots marked 1 (ring) and 2 (square)', cls: 'hf-gm__svg--left' });
          var right = drawGraph({ nodes: stim.right.nodes, edges: stim.right.edges }, { R: R, hit: true, letters: letters, label: 'Right drawing: choose the matching dots', cls: 'hf-gm__svg--right' });
          var picks = [];
          for (var q = 0; q < nTargets; q++) picks.push(null);
          var active = 0, onset = null, timer = null, offKeys = null;
          var prompt = h('p', { 'class': 'hf-gm__prompt', 'aria-live': 'polite' });
          var chips = [];
          for (var m = 0; m < nTargets; m++) {
            (function (mi) {
              var b = h('button', { type: 'button', 'class': 'hf-gm__chip hf-gm__chip--' + (mi + 1), 'aria-pressed': 'false' }, [
                h('span', { 'class': 'hf-gm__chipmark', 'aria-hidden': 'true' }, [String(mi + 1)]),
                h('span', { 'class': 'hf-gm__chipval' }, ['—'])
              ]);
              b.addEventListener('click', function () { if (onset !== null) { active = mi; paint(); } });
              chips.push(b);
            })(m);
          }
          var confirmBtn = h('button', { type: 'button', 'class': 'hf-btn hf-btn--primary', disabled: true }, [h('span', { 'class': 'hf-btn__label' }, ['Confirm']), h('kbd', { 'class': 'hf-kbd', 'aria-hidden': 'true' }, ['Enter'])]);
          var wrap = h('div', { 'class': 'hf-gm', style: 'visibility:hidden' }, [
            h('figure', { 'class': 'hf-gm__panel hf-gm__panel--left' }, [h('figcaption', { 'class': 'hf-gm__cap' }, ['Marked dots']), left.svg]),
            h('figure', { 'class': 'hf-gm__panel hf-gm__panel--right' }, [h('figcaption', { 'class': 'hf-gm__cap' }, ['Find their matches here']), right.svg]),
            h('div', { 'class': 'hf-gm__controls' }, [prompt, h('div', { 'class': 'hf-gm__chips', role: 'group', 'aria-label': 'Your choices' }, chips), confirmBtn])
          ]);
          F.stage.appendChild(wrap);
          F.setHint('Tap a dot, or type its letter (A–' + LETTERS.charAt(order.length - 1) + '). 1 or 2 switches the mark, Backspace clears it, Enter confirms.');

          function paint() {
            Object.keys(right.nodes).forEach(function (id) {
              var nd = right.nodes[id];
              k.clear(nd.dyn);
              var mi = picks.indexOf(+id);
              nd.g.classList.toggle('is-picked', mi >= 0);
              if (mi >= 0) {
                nd.dyn.appendChild(markShape(k.svg, nd.x, nd.y, R, mi + 1));
                nd.dyn.appendChild(k.svg('svg:text', { x: nd.x, y: nd.y + 2.6, 'class': 'hf-gm__marktext', 'text-anchor': 'middle' }, [String(mi + 1)]));
              }
            });
            chips.forEach(function (b, mi) {
              b.setAttribute('aria-pressed', mi === active ? 'true' : 'false');
              b.classList.toggle('is-active', mi === active);
              b.querySelector('.hf-gm__chipval').textContent = picks[mi] === null ? '—' : letters[picks[mi]];
              b.setAttribute('aria-label', 'Match for ' + (mi + 1) + ': ' + (picks[mi] === null ? 'not chosen' : 'dot ' + letters[picks[mi]]) + (mi === active ? ' (choosing now)' : ''));
            });
            var allSet = picks.every(function (p) { return p !== null; });
            confirmBtn.disabled = !picks.some(function (p) { return p !== null; });
            prompt.textContent = allSet ? 'Check your choices, then Confirm.' : ('Tap the dot that matches ' + (active + 1) + '.');
          }
          function place(id) {
            if (onset === null) return;
            var was = picks.indexOf(id);
            if (was >= 0 && was === active) { picks[was] = null; paint(); return; }
            if (was >= 0) picks[was] = null;
            picks[active] = id;
            // move on to the next mark that is still empty
            for (var s = 1; s <= picks.length; s++) {
              var cand = (active + s) % picks.length;
              if (picks[cand] === null) { active = cand; break; }
            }
            paint();
          }
          Object.keys(right.nodes).forEach(function (id) {
            var nd = right.nodes[id];
            nd.g.addEventListener('click', function () { place(+id); });
            // Space places the focused dot; Enter bubbles up and confirms (as everywhere else in this view)
            nd.g.addEventListener('keydown', function (e) {
              if (e.key === ' ' || e.code === 'Space') { e.preventDefault(); e.stopPropagation(); place(+id); }
            });
          });
          function cleanup() { clearTimeout(timer); if (offKeys) offKeys(); offKeys = null; clock.stop(); }
          function confirm(tEv) {
            if (onset === null || !picks.some(function (p) { return p !== null; })) return;
            cleanup();
            ctl.done({ i: t.i, response: picks.slice(), rt: Math.round((tEv - onset) * 10) / 10, voided: false, timedOut: false });
          }
          confirmBtn.addEventListener('click', function (e) { confirm(k.evTime(e)); });
          ctl.onCancel(cleanup);
          offKeys = k.keys(function (e, tEv) {
            if (onset === null) return;
            var L = k.letterOf(e);
            if (L && byLetter[L] !== undefined) { e.preventDefault(); place(byLetter[L]); return; }
            var d = k.digitOf(e);
            if (d && d <= picks.length) { e.preventDefault(); active = d - 1; paint(); return; }
            if (e.key === 'Backspace' || e.key === 'Delete') { e.preventDefault(); picks[active] = null; paint(); return; }
            if (e.key === 'Enter') {
              if (e.target && e.target.tagName === 'BUTTON' && e.target !== confirmBtn) return;
              e.preventDefault(); confirm(tEv);
            }
          });
          paint();
          k.frame().then(function (ts) {
            if (ctl.cancelled) return;
            wrap.style.visibility = '';
            onset = ts;
            clock.start(ts);
            timer = setTimeout(function () {
              cleanup();
              ctl.done({ i: t.i, response: picks.slice(), rt: null, voided: false, timedOut: true });
            }, windowMs);
          });
        });
      }

      function explain(t, res) {
        var resp = res.response || [];
        var right = !res.timedOut && t.answer.every(function (a, j) { return resp[j] === a; });
        // show the right answer on the right-hand drawing
        var svgR = F.stage.querySelector('.hf-gm__svg--right');
        if (svgR) {
          t.answer.forEach(function (id, j) {
            var g = svgR.querySelector('[data-node="' + id + '"]');
            if (g) g.classList.add('is-answer');
          });
        }
        var order = readingOrder(t.stim.right.nodes), letters = {};
        order.forEach(function (n, j) { letters[n.id] = LETTERS.charAt(j); });
        var text = t.answer.map(function (id, j) { return (j + 1) + ' → ' + letters[id]; }).join(', ');
        F.say(res.timedOut ? 'Time is up. The matches are ' + text + '.' : (right ? 'Right: ' + text + '.' : 'Not quite: the matches are ' + text + '.'), right ? 'good' : 'info');
        var row = h('div', { 'class': 'hf-actions' });
        F.answer.appendChild(h('div', { 'class': 'hf-lt__explain' }, [
          h('p', { 'class': 'hf-lt__why1' }, ['Tip: count the arrows going in and out of each marked dot, then look at its neighbours.']), row
        ]));
        var cb = F.stage.querySelector('.hf-gm__controls .hf-btn');
        if (cb) cb.disabled = true;
        return k.waitNext(row, 'Next');
      }
    }

    return {
      run: run,
      destroy: function () {
        destroyed = true;
        offs.splice(0).forEach(function (f) { try { f(); } catch (e) { /* ignore */ } });
        if (S) { S.stop(); S.destroy(); }
        if (F && F.el && F.el.parentNode) F.el.parentNode.removeChild(F.el);
      }
    };
  }

  HF.views['lab.graph'] = { create: create, drawGraph: drawGraph, readingOrder: readingOrder };
})(typeof window !== 'undefined' ? window : globalThis);
